// Entry customization, multiplayer skates, admin access and non-alcoholic snacks.
const assert=require('assert');
const {io}=require('socket.io-client');
const R=require('../public/roller');
const U='http://localhost:'+(process.env.PORT||8080);
const wait=ms=>new Promise(resolve=>setTimeout(resolve,ms));
const emit=(s,event,data)=>new Promise((resolve,reject)=>s.timeout(3000).emit(event,data,(err,r)=>err?reject(err):resolve(r)));
for(const r of R.ramps){
 assert.strictEqual(R.floorAt(r.lowX,r.z),0);
 assert.strictEqual(R.floorAt(r.topX,r.z),R.DJ.operatorH);
 assert(Math.abs(R.floorAt((r.lowX+r.topX)/2,r.z)-R.DJ.operatorH/2)<1e-8);
 assert.strictEqual(R.floorAt((r.lowX+r.topX)/2,R.DJ.rampZ0-.1),null,'ramps enter from the side');
}
assert.strictEqual(R.floorAt(10,50.8),R.DJ.operatorH);assert.strictEqual(R.floorAt(10,40),null);
assert.strictEqual(R.PALETTE.length,10);assert.strictEqual(new Set(R.PALETTE.map(p=>p[0])).size,10);
assert(R.PALETTE.some(([c])=>c===R.colours({skateBoot:'#f5f5f5'}).skateBoot),'legacy colour normalized');
(async()=>{
 const a=io(U,{forceNew:true}),b=io(U,{forceNew:true});
 const observed={players:{},doors:[],motion:[],jobs:[],done:[],eats:[],drinks:[],tables:{}};
 b.on('player',p=>observed.players[p.id]=p);
 b.on('rollerAlbaJob',d=>observed.jobs.push(d));b.on('albaDone',d=>observed.done.push(d));b.on('table',t=>observed.tables=t);b.on('eat',d=>observed.eats.push(d));b.on('drink',d=>observed.drinks.push(d));
 b.on('rollerDoor',d=>observed.doors.push(d.open));
 b.on('rollerMotion',d=>observed.motion.push(d));
 try{
  await Promise.all([new Promise(r=>a.on('connect',r)),new Promise(r=>b.on('connect',r))]);
  const unique=Date.now();
  await emit(a,'join',{nick:'롤러'+unique,clientId:'roller-'+unique});
  await emit(b,'join',{nick:'관객'+unique,clientId:'roller-watch-'+unique});
  const login=await fetch(U+'/admin/login',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({password:process.env.ADMIN_PASSWORD||'6651'})});
  const {token}=await login.json();
  assert.strictEqual((await emit(a,'setRollerDoor',{token:'invalid',open:false})).ok,false);
  assert.strictEqual((await emit(a,'setRollerDoor',{token,open:true})).ok,true);
  assert.strictEqual((await emit(a,'rollerTravel','enter')).ok,false,'must be at street entrance');
  a.emit('move',{pos:[R.ENTRY.x,0,R.ENTRY.z],rot:0});
  assert.strictEqual((await emit(a,'setRollerDoor',{token,open:false})).ok,true);
  assert.strictEqual((await emit(a,'rollerTravel','enter')).ok,false,'closed entrance');
  await emit(a,'setRollerDoor',{token,open:true});
  const entry=await emit(a,'rollerTravel','enter');
  assert(entry.ok);assert.deepStrictEqual(entry.pos,[R.ARRIVE.x,0,R.ARRIVE.z]);assert.strictEqual(entry.rollerSkates,false);
  let correction=null;a.once('rollerPosition',d=>correction=d);
  a.emit('move',{pos:[0,0,59],rot:0});await wait(150);
  assert.deepStrictEqual(correction.pos,entry.pos,'cannot move until skates selected');
  const equipped=await emit(a,'rollerEquip',{on:true,skateBoot:'#2685ff',skateWheel:'#faff00',skateLace:'invalid'});
  assert(equipped.ok);assert.strictEqual(equipped.skateLace,'#faff00');
  await wait(100);
  const seen=observed.players[a.id];assert(seen.rollerSkates);assert.strictEqual(seen.skateBoot,'#2685ff');assert.strictEqual(seen.skateWheel,'#faff00');
  a.emit('move',{pos:[R.CHANGE.x,0,R.CHANGE.z+1],rot:0});
  assert.strictEqual((await emit(a,'rollerEquip',{on:true,skateBoot:'#2685ff',skateWheel:'#faff00'})).ok,true,'change corner accepts customization');
  a.emit('move',{pos:[10,0,40],rot:0});
  assert.strictEqual((await emit(a,'rollerEquip',{on:true})).ok,false,'rink track cannot open customization');
  a.emit('rollerMotion','run');a.emit('rollerMotion','jump');await wait(100);
  assert.deepStrictEqual(observed.motion.slice(-2).map(x=>x.motion),['run','jump']);
  assert.strictEqual((await emit(a,'order','ramen')).ok,false,'must be seated at a dining table');
  assert(!R.seats.some(s=>s.table==='RB'),'wall benches removed');
  assert.strictEqual(R.DJ.h,.6);assert.strictEqual(R.DJ.operatorH,1);
  for(const seat of R.seats.filter(s=>s.table==='R1'))assert(((seat.x-9)/8.5)**2+((seat.z-40.7)/7.8)**2>1,'relocated seats clear roller track');
  const dining=R.seats.find(s=>s.table==='R1');a.emit('move',{pos:[dining.x,0,dining.z],rot:0});a.emit('seat',dining.id);await wait(100);
  assert.strictEqual((await emit(a,'order','soju')).ok,false,'roller menu is cup noodles and cider');
  assert.strictEqual((await emit(a,'order','ramen')).ok,true);await wait(750);
  assert.strictEqual((await emit(a,'order','cider')).ok,true);
  const deadline=Date.now()+30000;while(observed.done.filter(d=>d.table==='R1').length<2&&Date.now()<deadline)await wait(100);
  assert.strictEqual(observed.done.filter(d=>d.table==='R1').length,2,'both orders delivered');
  assert(observed.tables.R1.includes('ramen')&&observed.tables.R1.includes('cider'));
  assert.strictEqual(observed.jobs[0].kind,'ramen');assert(observed.jobs[0].route2.length>=3,'roller staff uses a clear aisle');
  a.emit('eat','ramen');a.emit('drink','cider');await wait(150);
  assert.strictEqual(observed.eats[0].kind,'ramen');assert.strictEqual(observed.drinks[0].type,'cider');
  assert.deepStrictEqual(R.MENU,['ramen','tteokbokki','cola','cider']);
  assert.strictEqual((await emit(a,'order','tteokbokki')).ok,true);await wait(750);
  assert.strictEqual((await emit(a,'order','cola')).ok,true);
  const secondDeadline=Date.now()+30000;while(observed.done.filter(d=>d.table==='R1').length<4&&Date.now()<secondDeadline)await wait(100);
  assert(observed.tables.R1.includes('tteokbokki')&&observed.tables.R1.includes('cola'));
  a.emit('eat','tteokbokki');a.emit('drink','cola');await wait(150);
  assert.strictEqual(observed.eats.at(-1).kind,'tteokbokki');assert.strictEqual(observed.drinks.at(-1).type,'cola');
  const sober=await emit(a,'join',{nick:'롤러'+unique,clientId:'roller-'+unique});assert.strictEqual(sober.resume.drinks.length,0,'cider is non-alcoholic');
  a.emit('seat',null);
  // Changing outfits keeps the chosen skate colours and equipped state.
  await emit(a,'profile',{nick:'롤러'+unique,style:'disco',skateBoot:'#2685ff',skateWheel:'#faff00'});await wait(100);
  assert.strictEqual(observed.players[a.id].rollerSkates,true);
  await emit(a,'setRollerDoor',{token,open:false});
  a.emit('move',{pos:[R.ARRIVE.x,0,R.ARRIVE.z],rot:0});
  const exit=await emit(a,'rollerTravel','exit');assert(exit.ok,'exit stays available when closed');assert.strictEqual(exit.rollerSkates,false);
  const resume=await emit(a,'join',{nick:'롤러'+unique,clientId:'roller-'+unique});
  assert.strictEqual(resume.resume.rollerSkates,false);
  await emit(a,'setRollerDoor',{token,open:true});
  // Walking through the ground-floor doorway uses the same access checks.
  a.emit('move',{pos:[R.ENTRY.x,0,R.ENTRY.z],rot:0});
  const crossed=new Promise(resolve=>a.once('rollerPosition',resolve));
  a.emit('move',{pos:[R.DOOR.x,0,R.DOOR.z+.1],rot:0});
  assert.strictEqual((await crossed).rollerSkates,false);
  assert.strictEqual((await emit(a,'rollerTravel','exit')).ok,true);
  await emit(a,'setRollerDoor',{token,open:false});
  assert.strictEqual((await emit(a,'adminAccess','invalid')).ok,false);
  assert.strictEqual((await emit(a,'rollerTravel','enter')).ok,false);
  assert.strictEqual((await emit(a,'adminAccess',token)).ok,true);
  assert.strictEqual((await emit(a,'rollerTravel','enter')).ok,true,'admin enters closed roller rink');
  assert.strictEqual((await emit(a,'rollerTravel','exit')).ok,true);
  await emit(a,'setRollerDoor',{token,open:true});
  // Closing the nightclub ejects regular visitors and keeps verified admins inside.
  await emit(a,'setClubDoor',{token,open:true});
  a.emit('move',{pos:[0,0,4],rot:0});b.emit('move',{pos:[0,0,4],rot:0});
  const guestEjected=new Promise(resolve=>b.once('accessPosition',resolve));
  await emit(a,'setClubDoor',{token,open:false});
  assert((await guestEjected).pos[2]>12);
  a.emit('move',{pos:[0,0,3],rot:0});
  const adminResume=await emit(a,'join',{nick:'롤러'+unique,clientId:'roller-'+unique});
  assert(adminResume.resume.pos[2]<12,'admin remains inside closed nightclub');
  const guestBlocked=new Promise(resolve=>b.once('accessPosition',resolve));
  b.emit('move',{pos:[0,0,4],rot:0});assert((await guestBlocked).pos[2]>12);
  await emit(a,'adminAccess',null);
  const formerAdminBlocked=new Promise(resolve=>a.once('accessPosition',resolve));
  a.emit('move',{pos:[0,0,2],rot:0});assert((await formerAdminBlocked).pos[2]>12);
  await emit(a,'setClubDoor',{token,open:true});
  const legacy=io(U,{forceNew:true});await new Promise(resolve=>legacy.on('connect',resolve));
  const restored=await emit(legacy,'join',{nick:'이전롤러'+unique,clientId:'legacy-roller-'+unique,last:{pos:[0,0,59],rollerSkates:true}});
  assert.deepStrictEqual(restored.resume.pos,[R.OFFSET.x,0,59+R.OFFSET.z],'saved old rink positions migrate');
  assert.strictEqual(restored.resume.rollerSkates,true);legacy.close();
  const removed=io(U,{forceNew:true});await new Promise(resolve=>removed.on('connect',resolve));
  const unseated=await emit(removed,'join',{nick:'이전의자'+unique,clientId:'removed-bench-'+unique,last:{worldVersion:2,pos:[21.5,.03,40],rollerSkates:true,seat:'RB-2'}});
  assert.strictEqual(unseated.resume.seat,null,'deleted bench seats do not restore');assert.strictEqual(unseated.resume.pos[1],0);removed.close();
  const moved=io(U,{forceNew:true});await new Promise(resolve=>moved.on('connect',resolve));
  const relocated=await emit(moved,'join',{nick:'이전테이블'+unique,clientId:'moved-table-'+unique,last:{worldVersion:2,pos:[14.8,.03,32.85],rollerSkates:true,seat:'R1-0'}});
  const target=R.seats.find(s=>s.id==='R1-0');assert.deepStrictEqual(relocated.resume.pos,[target.x,target.y,target.z],'saved seats follow moved table');moved.close();
  console.log('roller, legacy saves and closed-door admin access OK');
 }finally{a.close();b.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
